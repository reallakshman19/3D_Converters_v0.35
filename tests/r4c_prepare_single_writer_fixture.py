"""R4C one-writer + zero-mass source-endpoint witness regression.

All CII files are generated by the actual existing Python converter. No
private GLRD source or historical Owner approval material is committed.
"""
from __future__ import annotations
import argparse
import sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
sys.path.insert(0,str(ROOT/"tests"))
from r2_prepare_synthetic_fixture import generate as generate_r2
from r4a_prepare_lineage import generate as generate_r1
from roundtrip_foundation.snapshot_replay import capture_snapshot,run_existing_converter

OPTIONS={"coordsMode":"first","weightScale":"10",
         "splitCondensedValveFlange":True,
         "useRestraintTypeBasedOnJson":True,
         "stagedJsonPresent":False,"templateCiiPresent":False}
WRITER=(b"<ComponentRefNo>/SHARED-COMP</ComponentRefNo>"
        b"<Position>100 0 0</Position><OutsideDiameter>60.3</OutsideDiameter>"
        b"<WallThickness>3.9</WallThickness><Rigid>2</Rigid>"
        b"<Endpoint>2</Endpoint><Weight>15</Weight>")
def generate(out:Path)->None:
    generate_r2(out)
    original=(out/"original.xml").read_bytes()
    original_cii=(out/"original.cii").read_bytes()
    assert original.count(WRITER)==1
    revised=original.replace(WRITER,WRITER.replace(b"<Weight>15</Weight>",b"<Weight>2.6</Weight>"))
    assert revised.count(b"<ComponentRefNo>/SHARED-COMP</ComponentRefNo>")==2
    # Single component identity, one 15kg actual writer and one 0kg witness.
    assert original.count(b"<ComponentRefNo>/SHARED-COMP</ComponentRefNo>")==2
    assert revised.count(b"<ComponentRefNo>/SHARED-COMP</ComponentRefNo>")==2
    snapshot=capture_snapshot(
        engine_input_xml=revised,original_cii=b"R4C_SYNTHETIC_NOT_HISTORICAL",
        effective_config_json=b"{}",options=OPTIONS,assets={},
        run_id="R4C_ONE_WRITER_ZERO_WITNESS",
        completeness_attestation="COMPLETE_NO_EXTERNAL_MASTERS")
    revised_cii,_=run_existing_converter(snapshot,revised,b"{}",{})
    assert revised_cii!=original_cii
    (out/"r4c-approved.xml").write_bytes(revised)
    (out/"r4c-approved.cii").write_bytes(revised_cii)
    generate_r1(out)
    print("R4C_ONE_WRITER_ZERO_WITNESS_REAL_CONVERTER_READY")

if __name__=="__main__":
    p=argparse.ArgumentParser()
    p.add_argument("--output",type=Path,required=True)
    generate(p.parse_args().output)
