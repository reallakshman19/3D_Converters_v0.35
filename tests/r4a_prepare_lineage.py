"""Current-writer R4A synthetic frozen R1 lineage fixture.

Original/revised CII must first be generated by the existing converter.
This fixture is NOT the Owner's authentic 145 or historical 144 GLRD run.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import sys

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from roundtrip_foundation.snapshot_replay import (
    capture_snapshot, digest, replay_cii_without_edits,
)
from roundtrip_foundation.lineage import build_lineage_ledger, validate_lineage_ledger

OPTIONS={"coordsMode":"first","weightScale":"10",
         "splitCondensedValveFlange":True,
         "useRestraintTypeBasedOnJson":True,
         "stagedJsonPresent":False,"templateCiiPresent":False}


def generate(root:Path):
    xml=(root/"original.xml").read_bytes()
    original=(root/"original.cii").read_bytes()
    cfg=b"{}"
    snapshot=capture_snapshot(
        engine_input_xml=xml,original_cii=original,effective_config_json=cfg,
        options=OPTIONS,assets={},run_id="R4A_SYNTHETIC_CURRENT_WRITER",
        original_uploaded_xml=xml,
        completeness_attestation="COMPLETE_NO_EXTERNAL_MASTERS")
    replay=replay_cii_without_edits(
        conversion_snapshot=snapshot,engine_input_xml=xml,
        original_cii=original,effective_config_json=cfg,configuration_assets={})
    assert replay["verdict"]=="PASS_EXACT_REPLAY",replay
    lineage=build_lineage_ledger(
        conversion_snapshot=snapshot,engine_input_xml=xml,original_cii=original,
        effective_config_json=cfg,configuration_assets={},replay_report=replay)
    validated=validate_lineage_ledger(lineage,expected_snapshot=snapshot)
    assert validated["status"]=="PASS",validated
    report={
        "schema":"xml-cii-source-mass-browser-lineage/r4a",
        "status":"PASS_R1_STRUCTURAL_LINEAGE_WITH_UNATTESTED_MASS",
        "runIdentity":{
            "runId":"R4A_SYNTHETIC_CURRENT_WRITER",
            "sourceXmlSha256":digest(xml),
            "originalCiiSha256":digest(original),
            "configurationSha256":digest(cfg),
            "stagedJsonSha256":None,
            "originalUploadedXmlSha256":digest(xml),
            "snapshotFingerprint":snapshot["fingerprintSha256"],
            "converterCodeIdentity":snapshot["converter"]["codeIdentity"],
            "runtimeIdentity":snapshot["converter"]["runtimeIdentity"],
        },
        "noEditComparison":replay["comparison"],
        "sourceNodes":lineage["sourceNodes"],
        "pythonPreprocessedNodes":lineage["pythonPreprocessedNodes"],
        "elements":lineage["elements"],
        "auxiliaryRecords":[x for x in lineage["auxiliaryRecords"] if x["section"]=="RIGID"],
        "transformations":lineage["transformations"],
        "index":lineage["index"],
        "statistics":lineage["statistics"],
        "physicalMassAuthority":"NOT_ATTESTED","engineeringEditApproved":False,
    }
    (root/"r4a-r1-verified-lineage.json").write_text(
        json.dumps(report,indent=2,sort_keys=True,allow_nan=False)+"\n",encoding="utf-8")
    print("R4A_SYNTHETIC_VERIFIED",json.dumps({
        "sourceSha256":digest(xml),
        "ciiSha256":digest(original),
        "finalRigids":lineage["statistics"]["finalCiiRigids"],
        "transformedEvents":lineage["statistics"]["events"],
        "rigidOwnership":lineage["statistics"]["rigidOwnership"],
        "evidenceClass":"SYNTHETIC_CURRENT_WRITER_NOT_AUTHENTIC_GLRD",
    },sort_keys=True))


if __name__=="__main__":
    p=argparse.ArgumentParser()
    p.add_argument("--dir",type=Path,required=True)
    generate(p.parse_args().dir)
