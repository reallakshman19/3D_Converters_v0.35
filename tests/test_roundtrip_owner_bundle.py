"""Synthetic tests of private Owner intake; no private GLRD files used."""
from __future__ import annotations
import copy
import json
from pathlib import Path
import platform
import tempfile
import unittest

from roundtrip_foundation.owner_bundle_replay import (SCHEMA, inspect_bundle,
                                                     run_owner_bundle)
from roundtrip_foundation.snapshot_replay import (Hold, ENTRYPOINT, capture_snapshot,
                                                  converter_code_identity, digest,
                                                  run_existing_converter)
from roundtrip_foundation.generate_evidence import OPTIONS, FIXTURE, CONFIG

class OwnerBundleIntakeTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(prefix="private-owner-intake-test-")
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        xml = FIXTURE.read_bytes()
        bootstrap = capture_snapshot(
            engine_input_xml=xml, original_cii=b"GENERATE_TEST_CII",
            effective_config_json=CONFIG, options=OPTIONS, assets={},
            run_id="TEST_GENERATOR", completeness_attestation="COMPLETE_NO_EXTERNAL_MASTERS")
        cii, _ = run_existing_converter(bootstrap, xml, CONFIG, {})
        self.manifest = {
            "schema": SCHEMA,
            "runId": "SYNTHETIC_PRIVATE_INTAKE_TEST",
            "sourceStage": "ENGINE_INPUT_XML",
            "attestation": {
                "effectiveRunInputsComplete": True,
                "originalCiiIndependentlyRetained": True,
                "upstreamMastersComplete": True,
            },
            "converter": {
                "entrypoint": ENTRYPOINT, "codeIdentity": converter_code_identity(),
                "runtimeIdentity": {
                    "implementation": platform.python_implementation(),
                    "pythonVersion": platform.python_version(),
                },
            },
            "effectiveLineListSheet": "Linelist",
            "options": dict(OPTIONS),
            "artifacts": {},
            "pythonAssets": {},
            "upstreamAssets": [],
            "requiredUpstreamAssetRoles": [
                "line_list", "piping_class", "material_map", "weight_master"
            ],
            "note": "Synthetic test: baseline generated by current native converter, NOT authentic Owner CII",
        }
        for name, filename, data in (
            ("originalUploadedXml", "uploaded.xml", xml),
            ("engineInputXml", "engine-input.xml", xml),
            ("originalCii", "archived-original.cii", cii),
            ("effectiveConfigJson", "effective-support.json", CONFIG),
        ):
            self.manifest["artifacts"][name] = self.store(filename, data)
        for role in ("line_list", "piping_class", "material_map", "weight_master"):
            self.manifest["upstreamAssets"].append({
                "role": role, **self.store("masters/" + role + ".bin",
                                           ("synthetic-" + role).encode("ascii")),
            })
        self.save_manifest()

    def store(self, filename, data):
        path = self.root / filename
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        return {"path": filename, "sha256": digest(data), "bytes": len(data)}

    def save_manifest(self):
        (self.root / "run-custody.json").write_text(
            json.dumps(self.manifest, indent=2, sort_keys=True), encoding="utf-8")

    def assert_hold(self, expected):
        report, ledger = run_owner_bundle(self.root)
        self.assertEqual(report["status"], expected, report)
        self.assertIsNone(ledger)

    def test_private_frozen_existing_cii_replay_real_converter(self):
        report, ledger = run_owner_bundle(self.root)
        self.assertEqual(report["status"], "PASS_EXACT_REPLAY", report)
        self.assertIsNotNone(ledger)
        self.assertEqual(report["comparison"]["differingBytes"], 0)
        self.assertEqual(report["structure"]["elementCount"], 11)
        self.assertEqual(report["structure"]["rigidCount"], 6)
        self.assertTrue(ledger["readOnly"])
        self.assertEqual(report["effectiveLineListSheet"], "Linelist")
        self.assertEqual(report["physicalMassApproval"], "NOT_ATTESTED")

    def test_historical_sheet_is_preserved_not_silently_changed(self):
        self.manifest["effectiveLineListSheet"] = "Coversheet"
        self.save_manifest()
        report, _ = run_owner_bundle(self.root)
        self.assertEqual(report["status"], "PASS_EXACT_REPLAY")
        self.assertEqual(report["effectiveLineListSheet"], "Coversheet")
        self.assertTrue(report["configSelectionNotSilentlyCorrected"])

    def test_missing_archived_original_cii_refuses(self):
        (self.root / "archived-original.cii").unlink()
        self.assert_hold("HOLD_MISSING_INPUT")

    def test_edited_engine_xml_refuses_stale(self):
        p = self.root / "engine-input.xml"
        p.write_bytes(p.read_bytes().replace(b"<Weight>15</Weight>", b"<Weight>16</Weight>"))
        self.assert_hold("HOLD_STALE_SOURCE")

    def test_modified_original_cii_refuses(self):
        p = self.root / "archived-original.cii"
        p.write_bytes(p.read_bytes() + b"\n")
        self.assert_hold("HOLD_STALE_CII")

    def test_historic_cii_snapshot_does_not_match_current_converter(self):
        # This is a synthetic tampered historical baseline for the safety gate.
        p = self.root / "archived-original.cii"
        original = p.read_bytes()
        tampered = original.replace(b"02:00:00", b"03:00:00")
        self.assertNotEqual(tampered, original)
        self.manifest["artifacts"]["originalCii"] = self.store(
            "archived-original.cii", tampered)
        self.save_manifest()
        self.assert_hold("HOLD_NO_EDIT_PARITY")

    def test_missing_master_files_or_roles_refuse(self):
        (self.root / "masters/weight_master.bin").unlink()
        self.assert_hold("HOLD_MISSING_INPUT")
        self.manifest["upstreamAssets"] = self.manifest["upstreamAssets"][:-1]
        self.save_manifest()
        self.assert_hold("HOLD_MISSING_INPUT")


    def test_changed_effective_config_is_configuration_mismatch(self):
        p = self.root / "effective-support.json"
        p.write_bytes(b'{"unexpected": true}')
        self.assert_hold("HOLD_CONFIGURATION_MISMATCH")

    def test_changed_master_bytes_is_configuration_mismatch(self):
        p = self.root / "masters/piping_class.bin"
        p.write_bytes(b"modified synthetic master")
        self.assert_hold("HOLD_CONFIGURATION_MISMATCH")


    def test_declared_master_dependency_absent_refuses_even_with_valid_other_files(self):
        self.manifest["requiredUpstreamAssetRoles"].append("special_imported_support_master")
        self.save_manifest()
        self.assert_hold("HOLD_MISSING_INPUT")

    def test_only_actual_run_dependencies_required_not_hardcoded_four(self):
        # Real run might have no independent material/weight workbook, but must
        # still explicitly attest which imports were actually applied.
        self.manifest["requiredUpstreamAssetRoles"] = ["line_list", "piping_class"]
        self.manifest["upstreamAssets"] = [
            r for r in self.manifest["upstreamAssets"]
            if r["role"] in self.manifest["requiredUpstreamAssetRoles"]]
        self.save_manifest()
        report, ledger = run_owner_bundle(self.root)
        self.assertEqual(report["status"], "PASS_EXACT_REPLAY", report)
        self.assertEqual(report["requiredUpstreamAssetRoles"], ["line_list", "piping_class"])
        self.assertTrue(report["bundleFingerprintSha256"])
        self.assertIsNotNone(ledger)

    def test_missing_dependency_role_manifest_refuses(self):
        self.manifest.pop("requiredUpstreamAssetRoles")
        self.save_manifest()
        self.assert_hold("HOLD_MISSING_INPUT")

    def test_converter_identity_change_refuses(self):
        self.manifest["converter"]["codeIdentity"][ENTRYPOINT] = "stale"
        self.save_manifest()
        self.assert_hold("HOLD_CONVERTER_IDENTITY")

    def test_staged_flag_without_staged_bytes_refuses(self):
        self.manifest["options"]["stagedJsonPresent"] = True
        self.save_manifest()
        self.assert_hold("HOLD_MISSING_INPUT")

    def test_outside_bundle_symlink_or_parent_path_refuses(self):
        self.manifest["artifacts"]["effectiveConfigJson"]["path"] = "../not-private.json"
        self.save_manifest()
        self.assert_hold("HOLD_MISSING_INPUT")

    def test_attestation_missing_refuses(self):
        self.manifest["attestation"]["upstreamMastersComplete"] = False
        self.save_manifest()
        self.assert_hold("HOLD_MISSING_INPUT")

if __name__ == "__main__":
    unittest.main()
