ATTEST = "COMPLETE_NO_EXTERNAL_MASTERS"

def generate_context(xml=FIXTURE, *, options=None, config=CONFIG, assets=None, run_id="SYNTHETIC-MULTI"):
    options = dict(options or OPTIONS)
    assets = dict(assets or {})
    bootstrap = capture_snapshot(
        engine_input_xml=xml, original_cii=b"PROVISIONAL_NOT_CII",
        effective_config_json=config, options=options, assets=assets,
        run_id=run_id, completeness_attestation=ATTEST)
    cii, log = run_existing_converter(bootstrap, xml, config, assets)
    manifest = capture_snapshot(
        engine_input_xml=xml, original_cii=cii, effective_config_json=config,
        options=options, assets=assets, run_id=run_id,
        completeness_attestation=ATTEST, original_uploaded_xml=xml)
    return manifest, cii

def replay(snapshot, xml, cii, config=CONFIG, assets=None):
    return replay_cii_without_edits(
        conversion_snapshot=snapshot, engine_input_xml=xml,
        original_cii=cii, effective_config_json=config,
        configuration_assets={} if assets is None else assets)

def ledger_for(xml=FIXTURE, *, options=None, config=CONFIG, run_id="SYNTHETIC-MULTI"):
    snapshot, cii = generate_context(xml, options=options, config=config, run_id=run_id)
    result = replay(snapshot, xml, cii, config)
    assert result["verdict"] == "PASS_EXACT_REPLAY", result
    ledger = build_lineage_ledger(
        conversion_snapshot=snapshot, engine_input_xml=xml,
        original_cii=cii, effective_config_json=config,
        configuration_assets={}, replay_report=result)
    return snapshot, cii, result, ledger

def replace_aux_pointer(cii, element_index, value):
    lines = cii.decode("utf-8").splitlines(keepends=True)
    idx = next(i for i, x in enumerate(lines) if x.startswith("#$ ELEMENTS"))
    row = idx + 1 + (element_index - 1) * 15 + 12
    old = lines[row]
    # IEL row 13: first 15 columns, then RIGID index in 13 columns.
    lines[row] = old[:15] + str(value).rjust(13) + old[28:]
    return "".join(lines).encode("utf-8")


def synthetic_scale_xml(elements=433, rigids=144):
    """Explicitly synthetic scale witness; never the Owner's authentic GLRD."""
    assert elements == 433 and rigids == 144
    nodes = []
    for i in range(elements + 1):
        rigid = i > 0 and i % 3 == 1 and i <= 430
        fields = [
            f"<NodeNumber>{1000+i}</NodeNumber>",
            f"<ComponentType>{'RIGID' if rigid else 'PIPE'}</ComponentType>",
            f"<ComponentRefNo>/SCALE-{i}</ComponentRefNo>",
            f"<Position>{100*i} 0 0</Position>",
            "<OutsideDiameter>60.3</OutsideDiameter>",
            "<WallThickness>3.9</WallThickness>",
            f"<Weight>{15 if rigid else 0}</Weight>",
        ]
        if rigid:
            fields.append("<Rigid>2</Rigid><Endpoint>2</Endpoint>")
        nodes.append("<Node>" + "".join(fields) + "</Node>")
    return (
        "<PipeStressExport><RestrainOpenEnds>No</RestrainOpenEnds><Pipe>"
        "<Branch><Branchname>/SYNTHETIC-433-144</Branchname>"
        + "".join(nodes) + "</Branch></Pipe></PipeStressExport>"
    ).encode("utf-8")

class SnapshotReplayTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.snapshot, cls.cii = generate_context()
        cls.good = replay(cls.snapshot, FIXTURE, cls.cii)

    def check_hold(self, report, prefix):
        self.assertTrue(report["verdict"].startswith(prefix), report)
        self.assertFalse(report.get("publishable", False))

    def test_L16_exact_real_converter_replay(self):
        self.assertEqual(self.good["verdict"], "PASS_EXACT_REPLAY")
        cmp = self.good["comparison"]
        self.assertEqual(cmp["originalSha256"], cmp["replaySha256"])
        self.assertEqual(cmp["originalBytes"], cmp["replayBytes"])
        self.assertEqual(cmp["differingBytes"], 0)

    def test_multi_element_and_rigid_control_pointer_counts(self):
        integrity = self.good["structure"]
        self.assertGreaterEqual(integrity["elementCount"], 10)
        self.assertGreaterEqual(integrity["rigidCount"], 5)
        self.assertTrue(integrity["allPointersValid"])
        self.assertEqual(integrity["independentReparse"], "PASS")

    def test_L14_stale_source_refuses(self):
        self.check_hold(replay(self.snapshot, FIXTURE.replace(b"<Weight>15</Weight>",
                             b"<Weight>16</Weight>"), self.cii), "HOLD_STALE_SOURCE")

    def test_L15_missing_config_or_unattested_completeness_refuses(self):
        self.check_hold(replay(self.snapshot, FIXTURE, self.cii, b""), "HOLD_CONFIGURATION_MISMATCH")
        bad = copy.deepcopy(self.snapshot)
        bad["completeness"]["status"] = "UNRESOLVED"
        self.check_hold(replay(bad, FIXTURE, self.cii), "HOLD_CONFIGURATION_MISMATCH")

    def test_effective_config_mismatch_refuses(self):
        self.check_hold(replay(self.snapshot, FIXTURE, self.cii, b'{"overrides":{}}'),
                        "HOLD_CONFIGURATION_MISMATCH")

    def test_code_identity_mutation_refuses(self):
        bad = copy.deepcopy(self.snapshot)
        bad["converter"]["codeIdentity"]["xml_to_cii2019.py"] = "tampered"
        self.check_hold(replay(bad, FIXTURE, self.cii), "HOLD_CONFIGURATION_MISMATCH")

    def test_wrong_weight_scale_or_split_setting_refuses(self):
        bad = copy.deepcopy(self.snapshot)
        bad["configuration"]["weightScale"] = "1"
        self.check_hold(replay(bad, FIXTURE, self.cii), "HOLD_CONFIGURATION_MISMATCH")
        alternate = dict(OPTIONS, splitCondensedValveFlange=False)
        alternate_snap = capture_snapshot(
            engine_input_xml=FIXTURE, original_cii=self.cii,
            effective_config_json=CONFIG, options=alternate, assets={},
            run_id="ALTERED-SPLIT", completeness_attestation=ATTEST)
        self.check_hold(replay(alternate_snap, FIXTURE, self.cii), "HOLD_NO_EDIT_PARITY")

    def test_missing_asset_refuses(self):
        with self.assertRaises(Hold) as ctx:
            capture_snapshot(engine_input_xml=FIXTURE, original_cii=self.cii,
                effective_config_json=CONFIG,
                options=dict(OPTIONS, stagedJsonPresent=True),
                assets={}, run_id="MISSING-STAGED", completeness_attestation=ATTEST)
        self.assertEqual(ctx.exception.code, "HOLD_MISSING_INPUT")

    def test_unqualified_external_master_refuses(self):
        with self.assertRaises(Hold) as ctx:
            capture_snapshot(engine_input_xml=FIXTURE, original_cii=self.cii,
                effective_config_json=CONFIG, options=OPTIONS,
                assets={"unmapped_piping_master.xlsx": b"fixture"},
                run_id="MISSING-MASTER-MAPPING", completeness_attestation=ATTEST)
        self.assertEqual(ctx.exception.code, "HOLD_MISSING_INPUT")

    def test_modified_original_cii_refuses(self):
        self.check_hold(replay(self.snapshot, FIXTURE, self.cii + b" "), "HOLD_STALE_CII")

    def test_invalid_output_cii_cannot_pass_structure(self):
        with self.assertRaises(Hold) as ctx:
            validate_serialized_cii(b"#$ CONTROL\n1\n")
        self.assertEqual(ctx.exception.code, "HOLD_CII_INVALID")

    def test_snapshot_invocation_is_exact_no_implicit_flags(self):
        argv = build_argv(OPTIONS)
        self.assertIn("--split-condensed-valve-flange", argv)
        self.assertIn("--weight-scale", argv)
